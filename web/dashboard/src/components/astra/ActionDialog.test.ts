// Real-Chromium interaction tests for the ActionDialog two-field contract
// (blocking review, 2026-11-20): the shared dialog used to bind BOTH
// #action-dialog-input (amount) and #action-dialog-name (typed entity) to
// one state — independent real Chromium evidence showed typing the team id
// overwrote the amount and the corrupted value reached execute.
//
// These tests drive the REAL component tree (useAction + ActionDialog +
// useFocusTrap + i18n) in a real headless Chromium page. The harness entry
// is bundled with the repo's esbuild into node_modules/.cache (git-ignored)
// and injected into about:blank — no backend, no stand, no network.
//
// Contracts pinned by real typing:
//  - two-field: amount keeps its own state while the team id is typed
//    (both typing orders), confirm stays disabled until the EXACT entity is
//    typed, and execute receives ONLY the amount;
//  - entity-only consumers keep the historical semantics exactly: the typed
//    entity is the execute value;
//  - single-field (input-only) consumers are unchanged.
// Skipped (honestly) only when no Chromium build exists in this environment.

import { test, before } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const dashboard = join(here, '..', '..', '..')
const cacheDir = join(dashboard, 'node_modules', '.cache', 'action-dialog-test')

const harness = `// Generated by ActionDialog.test.ts (real-interaction harness).
import { createElement, useRef, useState } from 'react'
import { createRoot } from 'react-dom/client'
import { useAction } from ${JSON.stringify(join(here, 'ActionDialog.tsx'))}
import ${JSON.stringify(join(here, '..', '..', 'i18n', 'index.ts'))}

type Cfg = { entity: string; withInput: boolean; risk: 'high' | 'medium' }

function Harness() {
  const [cfg, setCfg] = useState<Cfg>({ entity: 'team-example', withInput: true, risk: 'high' })
  const cfgRef = useRef(cfg)
  cfgRef.current = cfg
  const action = useAction({ id: 'test.dialog', risk: cfg.risk, reversible: true })
  const g = globalThis as unknown as Record<string, unknown>
  g.__configure = (next: Partial<Cfg>) => setCfg({ ...cfgRef.current, ...next })
  g.__open = () => {
    const c = cfgRef.current
    void action.run({
      ...(c.entity ? { entity: c.entity } : {}),
      input: c.withInput ? { label: 'Monthly limit (USD)', initial: '50' } : undefined,
      confirmLabel: 'Confirm',
      execute: async (args: { value: string; reason: string }) => {
        const log = (g.__executed as Array<{ value: string; reason: string }>) ?? []
        log.push(args)
        g.__executed = log
      },
    })
  }
  return createElement('div', null, action.ui, createElement('button', { id: 'open-btn', onClick: () => (g.__open as () => void)() }, 'open'))
}

createRoot(document.getElementById('root') as HTMLElement).render(createElement(Harness))
`

let ready = false
let skipReason = ''

before(async () => {
  try {
    mkdirSync(cacheDir, { recursive: true })
    const entry = join(cacheDir, 'harness.tsx')
    writeFileSync(entry, harness)
    const esbuild = await import('esbuild')
    await esbuild.build({
      entryPoints: [entry],
      bundle: true,
      format: 'iife',
      outfile: join(cacheDir, 'harness.js'),
      absWorkingDir: dashboard,
      jsx: 'automatic',
      logLevel: 'silent',
    })
    const { chromium } = await import('@playwright/test')
    const browser = await chromium.launch()
    await browser.close()
    ready = true
  } catch (err) {
    skipReason = `harness unavailable: ${err instanceof Error ? err.message : String(err)}`
  }
})

async function withPage(fn: (page: import('@playwright/test').Page) => Promise<void>) {
  const { chromium } = await import('@playwright/test')
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage()
    await page.setContent('<!doctype html><html><body><div id="root"></div></body></html>')
    await page.addScriptTag({ path: join(cacheDir, 'harness.js') })
    await fn(page)
  } finally {
    await browser.close()
  }
}

const confirmDisabled = (page: import('@playwright/test').Page) =>
  page.evaluate(() => (document.querySelector('[role="dialog"] button.btn-primary') as HTMLButtonElement | null)?.disabled ?? true)

test('two-field: typing the team id never touches the amount — evidence order (amount first, then team)', async t => {
  if (!ready) return t.skip(skipReason)
  await withPage(async page => {
    await page.click('#open-btn')
    await page.waitForSelector('[role="dialog"]')
    assert.equal(await page.inputValue('#action-dialog-input'), '50', 'amount starts at its initial value')
    assert.equal(await page.inputValue('#action-dialog-name'), '', 'typed-entity field starts empty')
    assert.equal(await confirmDisabled(page), true, 'confirm disabled while the entity is not typed')
    await page.fill('#action-dialog-input', '50')
    await page.fill('#action-dialog-name', 'team-example')
    // THE corrupted contract, asserted live: the amount is still the amount.
    assert.equal(await page.inputValue('#action-dialog-input'), '50', 'amount survives typing the team id')
    assert.equal(await page.inputValue('#action-dialog-name'), 'team-example', 'name field holds the typed entity')
    assert.equal(await confirmDisabled(page), false, 'exact entity enables confirm')
    await page.click('[role="dialog"] button.btn-primary')
    await page.waitForSelector('[role="dialog"]', { state: 'detached' })
    const executed = await page.evaluate(() => (globalThis as { __executed?: unknown }).__executed)
    assert.deepEqual(executed, [{ value: '50', reason: '' }], 'execute receives ONLY the amount — never the team id')
  })
})

test('two-field: reverse order (entity first, then amount) and a wrong entity stays blocked', async t => {
  if (!ready) return t.skip(skipReason)
  await withPage(async page => {
    await page.click('#open-btn')
    await page.waitForSelector('[role="dialog"]')
    await page.fill('#action-dialog-name', 'team-example')
    await page.fill('#action-dialog-input', '50')
    assert.equal(await page.inputValue('#action-dialog-name'), 'team-example', 'entity survives editing the amount')
    await page.fill('#action-dialog-name', 'wrong-team')
    assert.equal(await confirmDisabled(page), true, 'wrong entity keeps confirm disabled')
    await page.fill('#action-dialog-name', 'team-example')
    assert.equal(await confirmDisabled(page), false)
    await page.click('[role="dialog"] button.btn-primary')
    await page.waitForSelector('[role="dialog"]', { state: 'detached' })
    const executed = await page.evaluate(() => (globalThis as { __executed?: unknown }).__executed)
    assert.deepEqual(executed, [{ value: '50', reason: '' }])
  })
})

test('entity-only consumers keep the historical semantics: the typed entity IS the execute value', async t => {
  if (!ready) return t.skip(skipReason)
  await withPage(async page => {
    await page.evaluate(() => (globalThis as { __configure?: (c: unknown) => void }).__configure?.({ withInput: false }))
    await page.click('#open-btn')
    await page.waitForSelector('[role="dialog"]')
    assert.equal(await page.locator('#action-dialog-input').count(), 0, 'no amount field without input')
    await page.fill('#action-dialog-name', 'team-example')
    assert.equal(await confirmDisabled(page), false)
    await page.click('[role="dialog"] button.btn-primary')
    await page.waitForSelector('[role="dialog"]', { state: 'detached' })
    const executed = await page.evaluate(() => (globalThis as { __executed?: unknown }).__executed)
    assert.deepEqual(executed, [{ value: 'team-example', reason: '' }], 'entity-only execute value is the typed entity (unchanged)')
  })
})

test('single-field (input-only, medium risk) consumers are unchanged', async t => {
  if (!ready) return t.skip(skipReason)
  await withPage(async page => {
    await page.evaluate(() => (globalThis as { __configure?: (c: unknown) => void }).__configure?.({ risk: 'medium' }))
    await page.click('#open-btn')
    await page.waitForSelector('[role="dialog"]')
    assert.equal(await page.locator('#action-dialog-name').count(), 0, 'no typed-entity field at medium risk')
    await page.fill('#action-dialog-input', '25')
    assert.equal(await confirmDisabled(page), false)
    await page.click('[role="dialog"] button.btn-primary')
    await page.waitForSelector('[role="dialog"]', { state: 'detached' })
    const executed = await page.evaluate(() => (globalThis as { __executed?: unknown }).__executed)
    assert.deepEqual(executed, [{ value: '25', reason: '' }])
  })
})
