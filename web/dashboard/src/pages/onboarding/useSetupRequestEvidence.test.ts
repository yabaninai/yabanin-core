let browser: import('@playwright/test').Browser | null = null
let server: import('node:http').Server | null = null
let base = ''

before(async () => {
  mkdirSync(cacheDir, { recursive: true })
  const entry = join(cacheDir, 'harness.tsx')
  writeFileSync(entry, harness)
  const esbuild = await import('esbuild')
  await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    outfile: join(cacheDir, 'harness.js'),
    absWorkingDir: dashboard,
    jsx: 'automatic',
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'silent',
  })
  server = createServer((_req, res) => {
    res.setHeader('content-type', 'text/html')
    res.end('<!doctype html><html><body><div id="root"></div></body></html>')
  })
  await new Promise<void>(resolve => server!.listen(0, '127.0.0.1', resolve))
  const addr = server!.address()
  if (!addr || typeof addr === 'string') throw new Error('no server address')
  base = `http://127.0.0.1:${addr.port}`
  const { chromium } = await import('@playwright/test')
  browser = await chromium.launch()
})

after(async () => {
  if (browser) await browser.close()
  if (server) await new Promise(resolve => server!.close(resolve))
})

type Page = import('@playwright/test').Page

async function openPage(fragment: string): Promise<Page> {
  const page = await browser!.newPage()
  await page.goto(`${base}/${fragment}`)
  await page.evaluate(() => {
    try { localStorage.clear() } catch { /* best-effort */ }
  })
  await page.addScriptTag({ path: join(cacheDir, 'harness.js') })
  await page.evaluate(() => {
    ;(globalThis as unknown as { __start: (id: string) => void }).__start('Evidence')
  })
  return page
}

type EvState = { org: string; request: string; evidence: string | null; state: string }

// The mount renders before the first effect, so every observation must wait
// for the SETTLED state it asserts on — never just for the probe to exist.
const waitEv = (page: Page, want: { state?: string; evidence?: string | null }) =>
  page.waitForFunction((w: { state?: string; evidence?: string | null }) => {
    const el = document.querySelector('#ev')
    if (!el || !el.textContent) return false
    const s = JSON.parse(el.textContent) as EvState
    if (w.state !== undefined && s.state !== w.state) return false
    if (w.evidence !== undefined && s.evidence !== w.evidence) return false
    return true
  }, want).then(() => page.evaluate(() => (JSON.parse(document.querySelector('#ev')!.textContent!) as EvState)))

const typeAndVerify = async (page: Page, id: string) => {
  await page.getByTestId('welcome-setup-request-input').fill(id)
  await page.getByTestId('welcome-setup-request-verify').click()
}

test('(1) a failed lookup is unavailable — never not-found — and the same id retries healthy through the existing control', async () => {
  const page = await openPage('#onboarding?org=orgA&lang=en')
  try {
    await page.evaluate(() => { (globalThis as unknown as { __failNext: number }).__failNext = 1 })
    await typeAndVerify(page, 'r1')

    // the failed read answers the honest unavailable state, org-bound
    let ev = await waitEv(page, { state: 'unavailable', evidence: null })
    assert.equal(ev.evidence, null, 'a failed lookup proves nothing — no evidence identity')
    const fetches = await page.evaluate(() => (globalThis as unknown as { __requestsFetches: Array<{ org: string; requestId: string }> }).__requestsFetches)
    assert.deepEqual(fetches, [{ org: 'orgA', requestId: 'r1' }], 'the lookup stays bound to the scoped org')

    const unavailable = page.getByTestId('welcome-setup-request-unavailable')
    assert.ok(await unavailable.isVisible(), 'the unavailable hint renders')
    assert.match((await unavailable.textContent()) ?? '', /\S/, 'the unavailable hint is non-empty localized copy')
    assert.equal(await page.getByTestId('welcome-setup-request-invalid').count(), 0, 'a failed lookup must never render the not-found claim')
    assert.equal(await page.getByTestId('welcome-first-request-link').count(), 0)
    const role = await unavailable.getAttribute('role')
    assert.equal(role, 'alert', 'the failure hint is announced')

    // retry the SAME id through the existing Verify control — the URL param
    // does not change, so this exercises the explicit retry path
    await page.evaluate(() => { (globalThis as unknown as { __failNext: number }).__failNext = 0 })
    await page.getByTestId('welcome-setup-request-verify').click()

    ev = await waitEv(page, { state: 'idle', evidence: 'r1' })
    assert.equal(ev.state, 'idle')
    assert.equal(ev.evidence, 'r1')
    assert.equal(await page.getByTestId('welcome-setup-request-unavailable').count(), 0, 'the recovered retry clears the unavailable hint')
    assert.equal(await page.getByTestId('welcome-setup-request-invalid').count(), 0)
    const link = page.getByTestId('welcome-first-request-link')
    assert.ok(await link.isVisible(), 'the verified id renders the evidence link')
    assert.match(await link.getAttribute('href') ?? '', /requests-explorer/)
    assert.match(await link.getAttribute('href') ?? '', /org=orgA/, 'the link stays org-bound')
    const fetchesAfter = await page.evaluate(() => (globalThis as unknown as { __requestsFetches: Array<{ org: string; requestId: string }> }).__requestsFetches)
    assert.deepEqual(fetchesAfter, [
      { org: 'orgA', requestId: 'r1' },
      { org: 'orgA', requestId: 'r1' },
    ], 'the same-id retry re-ran the org-scoped lookup exactly once')
  } finally { await page.close() }
})

test('(2) a successful read with no row is the only path to the verified no-match', async () => {
  const page = await openPage('#onboarding?org=orgA&lang=en')
  try {
    await typeAndVerify(page, 'zz')

    const ev = await waitEv(page, { state: 'invalid', evidence: null })
    assert.equal(ev.state, 'invalid')
    assert.equal(ev.evidence, null)
    const invalid = page.getByTestId('welcome-setup-request-invalid')
    assert.ok(await invalid.isVisible(), 'the verified no-match renders the not-found copy')
    assert.match((await invalid.textContent()) ?? '', /\S/)
    assert.equal(await invalid.getAttribute('role'), 'alert')
    assert.equal(await page.getByTestId('welcome-setup-request-unavailable').count(), 0, 'a verified no-match is not a lookup failure')
    assert.equal(await page.getByTestId('welcome-first-request-link').count(), 0)
  } finally { await page.close() }
})

test('(3) a stale response never commits an identity for a view that moved on', async () => {
  const page = await openPage('#onboarding?org=orgA&lang=en')
  try {
    await page.evaluate(() => { (globalThis as unknown as { __holdNext: boolean }).__holdNext = true })
    await typeAndVerify(page, 'r1')
    let ev = await waitEv(page, { state: 'checking', evidence: null })
    assert.equal(ev.state, 'checking', 'the held lookup keeps the checking state')

    // the view moves on: same id, different org — the effect re-runs and
    // cancels the held run
    await page.evaluate(() => { location.hash = '#onboarding?org=orgB&request=r1&lang=en' })
    ev = await waitEv(page, { state: 'invalid', evidence: null })
    assert.equal(ev.org, 'orgB', 'the view moved to the new org')
    assert.equal(ev.evidence, null)
    assert.equal(await page.getByTestId('welcome-first-request-link').count(), 0)

    // only NOW the stale orgA response resolves with a matching row — it
    // must not resurrect the identity for the orgB view
    await page.evaluate(() => { (globalThis as unknown as { __release: () => void }).__release() })
    await new Promise(resolve => setTimeout(resolve, 400))
    ev = await page.evaluate(() => (JSON.parse(document.querySelector('#ev')!.textContent!) as EvState))
    assert.equal(ev.state, 'invalid', 'the stale response must not flip the state')
    assert.equal(ev.evidence, null, 'the stale response must not commit its identity')
    assert.equal(await page.getByTestId('welcome-first-request-link').count(), 0)
    const fetches = await page.evaluate(() => (globalThis as unknown as { __requestsFetches: Array<{ org: string; requestId: string }> }).__requestsFetches)
    assert.deepEqual(fetches.map(f => f.org), ['orgA', 'orgB'], 'both lookups stay org-bound')
  } finally { await page.close() }
})

test('(4) the existing healthy path is unchanged (changed id, exactly one lookup)', async () => {
  const page = await openPage('#onboarding?org=orgA&lang=en')
  try {
    await typeAndVerify(page, 'r1')

    const ev = await waitEv(page, { state: 'idle', evidence: 'r1' })
    assert.equal(ev.state, 'idle')
    assert.equal(ev.evidence, 'r1')
    const link = page.getByTestId('welcome-first-request-link')
    assert.ok(await link.isVisible())
    assert.match(await link.getAttribute('href') ?? '', /org=orgA/)
    const fetches = await page.evaluate(() => (globalThis as unknown as { __requestsFetches: Array<{ org: string; requestId: string }> }).__requestsFetches)
    assert.deepEqual(fetches, [{ org: 'orgA', requestId: 'r1' }], 'a changed id performs exactly one lookup — no double fire')
    assert.equal(await page.getByTestId('welcome-setup-request-invalid').count(), 0)
    assert.equal(await page.getByTestId('welcome-setup-request-unavailable').count(), 0)
  } finally { await page.close() }
})
