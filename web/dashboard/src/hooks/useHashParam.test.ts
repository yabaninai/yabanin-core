let browser: import('@playwright/test').Browser | null = null
let server: import('node:http').Server | null = null
let base = ''

before(async () => {
  mkdirSync(cacheDir, { recursive: true })
  const entry = join(cacheDir, 'harness.tsx')
  writeFileSync(entry, harness)
  const esbuild = await import('esbuild')
  await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    outfile: join(cacheDir, 'harness.js'),
    absWorkingDir: dashboard,
    jsx: 'automatic',
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'silent',
  })
  server = createServer((_req, res) => {
    res.setHeader('content-type', 'text/html')
    res.end('<!doctype html><html><body><div id="root"></div></body></html>')
  })
  await new Promise<void>(resolve => server!.listen(0, '127.0.0.1', resolve))
  const addr = server!.address()
  if (!addr || typeof addr === 'string') throw new Error('no server address')
  base = `http://127.0.0.1:${addr.port}`
  const { chromium } = await import('@playwright/test')
  browser = await chromium.launch()
})

after(async () => {
  if (browser) await browser.close()
  if (server) await new Promise(resolve => server!.close(resolve))
})

type Page = import('@playwright/test').Page

async function openPage(fragment: string, mount: string, lastOrg?: string): Promise<Page> {
  const page = await browser!.newPage()
  await page.goto(`${base}/${fragment}`)
  await page.evaluate((org: string | undefined) => {
    try { localStorage.clear() } catch { /* best-effort */ }
    if (org) localStorage.setItem('yabanin.orgScope.v1', org)
  }, lastOrg)
  await page.addScriptTag({ path: join(cacheDir, 'harness.js') })
  await page.evaluate((id: string) => {
    ;(globalThis as unknown as { __start: (i: string) => void }).__start(id)
  }, mount)
  return page
}

const outText = (page: Page) => page.locator('#out').textContent()

test('(a) actual link navigation re-adopts the param; Back and Forward follow the history entries', async () => {
  const page = await openPage('#settings?tab=general&lang=en', 'Scope')
  try {
    assert.equal(JSON.parse((await outText(page))!).tab, 'general', 'mount reads the initial hash')
    await page.click('#link-display')
    await page.waitForURL(/#settings\?tab=display&lang=en$/)
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).tab === 'display')
    assert.ok(await page.evaluate(() => (globalThis as unknown as { __hashEvents: number }).__hashEvents >= 1), 'a real hashchange fired')
    await page.goBack()
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).tab === 'general')
    await page.goForward()
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).tab === 'display')
    // the unrelated language param survived every step
    assert.match(page.url(), /lang=en$/)
  } finally { await page.close() }
})

test('(a-org) hashchange org switch updates the org consumer; Back/Forward return orgA then orgB', async () => {
  const page = await openPage('#onboarding?org=orgA&request=r1', 'Scope')
  try {
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgA')
    await page.evaluate(() => { location.hash = '#onboarding?org=orgB&request=r1' })
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgB')
    await page.evaluate(() => history.back())
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgA')
    await page.evaluate(() => history.forward())
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgB')
  } finally { await page.close() }
})

test('(b) the setup-request identity revalidates against the NEW org — a known id must not stay accepted under a foreign org', async () => {
  const page = await openPage('#onboarding?org=orgA&request=r1', 'Evidence')
  try {
    await page.waitForFunction(() => {
      const s = JSON.parse(document.querySelector('#ev')!.textContent!)
      return s.evidence === 'r1' && s.org === 'orgA'
    }, null, { timeout: 5000 })
    await page.evaluate(() => { location.hash = '#onboarding?org=orgB&request=r1' })
    await page.waitForFunction(() => {
      const s = JSON.parse(document.querySelector('#ev')!.textContent!)
      return s.org === 'orgB' && s.evidence === null && s.entry === 'invalid'
    }, null, { timeout: 5000 })
    // Back re-validates against orgA again — no stale facts survive either way
    await page.evaluate(() => history.back())
    await page.waitForFunction(() => {
      const s = JSON.parse(document.querySelector('#ev')!.textContent!)
      return s.org === 'orgA' && s.evidence === 'r1'
    }, null, { timeout: 5000 })
  } finally { await page.close() }
})

test('(c) OrgSelect with an absent cached org exposes the __unknown__ option without adopting the sentinel', async () => {
  const page = await openPage('#settings', 'OrgHost')
  try {
    // options of a closed <select> have no visible box — attached is the
    // honest state; the control itself must be visible and interactive.
    const sentinel = page.locator('option[value="__unknown__"]')
    await page.locator('select.control').waitFor({ state: 'visible', timeout: 5000 })
    await sentinel.waitFor({ state: 'attached', timeout: 5000 })
    assert.match(await sentinel.textContent() ?? '', /org-foreign/, 'the option surfaces the foreign id verbatim')
    await page.selectOption('select', '__unknown__')
    const changes = await page.evaluate(() => (globalThis as unknown as { __orgChanges: string[] }).__orgChanges)
    assert.ok(!changes.includes('__unknown__'), 'the sentinel never reaches the caller as an org id')
    assert.deepEqual(changes, ['org-foreign'], 'selecting the sentinel keeps the same (foreign) org')
    // The select's machine value is the sentinel BY DESIGN (that is what
    // makes the option addressable); what the operator SEES is the
    // "ID: org-foreign" label — never a raw sentinel string.
    const shown = await page.evaluate(() => (document.querySelector('select') as HTMLSelectElement).selectedOptions[0]?.textContent ?? '')
    assert.match(shown, /org-foreign/, 'display keeps the foreign id label, not a sentinel string')
  } finally { await page.close() }
})

test('(d) repeated setters rewrite in place — no hashchange loop, no history growth, params preserved', async () => {
  const page = await openPage('#settings?tab=general&lang=en', 'Scope')
  try {
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).tab === 'general')
    const before = await page.evaluate(() => ({ len: history.length, ev: (globalThis as unknown as { __hashEvents: number }).__hashEvents }))
    await page.click('#set-tab')
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).tab === 'theme')
    await page.click('#set-tab')
    await page.click('#set-tab')
    const after = await page.evaluate(() => ({ len: history.length, ev: (globalThis as unknown as { __hashEvents: number }).__hashEvents }))
    assert.equal(after.ev, before.ev, 'replaceState commits fire no hashchange — no adoption loop')
    assert.equal(after.len, before.len, 'no duplicate history entries from repeated setters')
    assert.match(page.url(), /#settings\?tab=theme&lang=en$/, 'path and the unrelated lang param are preserved')
  } finally { await page.close() }
})

test('(legacy) last-org memory still seeds a hash without org, and adoption never rewrites it', async () => {
  const page = await openPage('#onboarding', 'Scope', 'orgZ')
  try {
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgZ')
    await page.evaluate(() => { location.hash = '#onboarding?org=orgB' })
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgB')
    // removing the org param again falls back to the UNTOUCHED memory
    await page.evaluate(() => { location.hash = '#onboarding' })
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).org === 'orgZ')
    assert.equal(await page.evaluate(() => localStorage.getItem('yabanin.orgScope.v1')), 'orgZ', 'adoption does not rewrite the remembered org')
  } finally { await page.close() }
})


test('(shared-store) setPeriod updates URL, shared store and mounted hook without growing history', async () => {
  const page = await openPage('#report?period=7d', 'PeriodScope')
  try {
    await page.waitForFunction(() => JSON.parse(document.querySelector('#out')!.textContent!).period === '7d')
    const historyBefore = await page.evaluate(() => history.length)
    await page.click('#period-30')
    await page.waitForFunction(() => {
      const state = JSON.parse(document.querySelector('#out')!.textContent!)
      return state.period === '30d' && state.storePeriod === '30d'
    })
    assert.match(page.url(), /#report\?period=30d$/)
    assert.equal(await page.evaluate(() => history.length), historyBefore, 'shared replaceState commits add no history entry')
  } finally { await page.close() }
})

test('(inspect-navigation) native links, Back/Forward and setters keep inspector state bound to the exact URL', async () => {
  const page = await openPage('#requests-explorer?org=orgA&inspect=request%3Ar1&lang=en', 'InspectHost')
  try {
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === 'request:r1')
    await page.click('#nav-plain')
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === '')
    assert.match(page.url(), /#requests-explorer\?org=orgB&lang=en$/, 'plain navigation removes only the inspector')
    await page.goBack()
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === 'request:r1')
    await page.goForward()
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === '')
    const historyBefore = await page.evaluate(() => history.length)
    await page.click('#inspect-open')
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === 'request:r2')
    assert.match(page.url(), /#requests-explorer\?org=orgB&lang=en&inspect=request%3Ar2$/, 'setter preserves one hash, locale and scope')
    assert.equal(await page.evaluate(() => history.length), historyBefore, 'open is view state, not a new history entry')
    await page.click('#inspect-close')
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === '')
    assert.match(page.url(), /#requests-explorer\?org=orgB&lang=en$/)
    await page.evaluate(() => { location.hash = '#requests-explorer?org=orgB&lang=en&inspect=request%3Ar2' })
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === 'request:r2')
    await page.goBack()
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === '')
    await page.goForward()
    await page.waitForFunction(() => document.querySelector('#out')!.textContent === 'request:r2')
  } finally { await page.close() }
})

test('(label-scope) a late response from the previous org cannot replace the current scoped labels', async () => {
  const page = await openPage('#requests-explorer?org=orgA', 'LabelHost')
  const requests = () => page.evaluate(() => (globalThis as unknown as {
    __labelRequests: Array<{ org: string; from: string; to: string }>
  }).__labelRequests)
  const resolve = (org: string) => page.evaluate((id) => {
    ;(globalThis as unknown as { __labelResolvers: Record<string, () => void> }).__labelResolvers[id]?.()
  }, org)
  try {
    await page.waitForFunction(() => (globalThis as unknown as { __labelRequests: Array<{ org: string }> }).__labelRequests.some(r => r.org === 'orgA'))
    await page.evaluate(() => { location.hash = '#requests-explorer?org=orgB' })
    await page.waitForFunction(() => (globalThis as unknown as { __labelRequests: Array<{ org: string }> }).__labelRequests.some(r => r.org === 'orgB'))
    await resolve('orgB')
    await page.waitForFunction(() => document.querySelector('#labels')!.textContent === 'label-orgB')
    await resolve('orgA')
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => resolve())))
    assert.equal(await page.locator('#labels').textContent(), 'label-orgB', 'stale orgA must not overwrite the current orgB labels')
    const reads = await requests()
    assert.ok(reads.some(r => r.org === 'orgA' && r.from && r.to), 'initial scoped label request observed')
    assert.ok(reads.some(r => r.org === 'orgB' && r.from && r.to), 'navigated scoped label request observed')
  } finally { await page.close() }
})
