package license

import (
	"crypto/ed25519"
	"encoding/hex"
	"fmt"
)

//go:generate go run keys_gen.go

// mustVendorKey decodes a hex-encoded Ed25519 public key into raw bytes. It
// panics at init if the value is not valid hex or not exactly 32 bytes: a bad
// build-time-embedded vendor key is a fatal deployment error, not a runtime
// condition to recover from. This prevents the regression where a hex STRING is
// cast directly to ed25519.PublicKey (yielding 64 ASCII bytes that ed25519.Verify
// silently rejects for every token).
func mustVendorKey(hexKey string) ed25519.PublicKey {
	b, err := hex.DecodeString(hexKey)
	if err != nil {
		panic(fmt.Sprintf("license: vendor public key is not valid hex: %v", err))
	}
	if len(b) != ed25519.PublicKeySize {
		panic(fmt.Sprintf("license: vendor public key must be %d bytes, got %d", ed25519.PublicKeySize, len(b)))
	}
	return ed25519.PublicKey(b)
}

