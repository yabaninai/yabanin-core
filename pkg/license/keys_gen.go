//go:build ignore

package main

import (
	"crypto/ed25519"
	"encoding/hex"
	"fmt"
	"os"
)

func main() {
	// Support both old and new env var names for backward compatibility
	pubkeyHex := os.Getenv("YABANIN_LICENSE_ROOT_PUBKEY")
	if pubkeyHex == "" {
		pubkeyHex = os.Getenv("YABANIN_LICENSE_VENDOR_PUBKEY")
	}

	var pub ed25519.PublicKey
	var err error

	if pubkeyHex != "" {
		pub, err = hex.DecodeString(pubkeyHex)
		if err != nil || len(pub) != ed25519.PublicKeySize {
			fmt.Fprintf(os.Stderr, "error: key must be 64 hex chars (32 bytes)\n")
			os.Exit(1)
		}
	} else {
		// Generate test key for development
		_, priv, err := ed25519.GenerateKey(nil)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error generating test key: %v\n", err)
			os.Exit(1)
		}
		pub = priv.Public().(ed25519.PublicKey)
	}

	// Generate code that stores the key as a hex constant and decodes it to bytes
	// at init via mustVendorKey (defined in keys.go). Casting the hex STRING directly
	// to ed25519.PublicKey produces a 64-byte ASCII value that ed25519.Verify always
	// rejects — the decoded-bytes form is the only correct representation.
	code := fmt.Sprintf(`// Code generated by keys_gen.go; DO NOT EDIT.
// Generated from YABANIN_LICENSE_ROOT_PUBKEY or YABANIN_LICENSE_VENDOR_PUBKEY env var.

package license

// vendorPublicKeyHex is the root Ed25519 public key for license verification,
// hex-encoded (64 chars = 32 bytes). It is decoded to raw bytes at init by
// mustVendorKey (see keys.go) so a malformed value fails fast at startup instead
// of producing a 64-byte ASCII "key" that silently never verifies.
const vendorPublicKeyHex = %q

// VendorPublicKey is the decoded 32-byte root Ed25519 public key.
var VendorPublicKey = mustVendorKey(vendorPublicKeyHex)
`, hex.EncodeToString(pub))

	if err := os.WriteFile("zz_keys.go", []byte(code), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "error writing zz_keys.go: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Generated zz_keys.go (%d hex chars)\n", len(pub)*2)
}
