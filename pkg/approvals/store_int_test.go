// Docker-backed acceptance flows on the production-migration stand. These
// probes cover what stubs cannot honestly reproduce: the five-state
// lifecycle over real rows, the atomic decision-vs-expiry race, restart
// durability (fresh Store instance, same durable rows) and the resume
// projection.
//
// The only time lever a test needs is short real TTLs (1s) plus a
// time-travel UPDATE for aging a row past its deadline without waiting —
// time travel is otherwise not a product feature.

type approvalFixture struct {
	pool *pgxpool.Pool
	org  string // org id the operations bind to (uuid string)
}

func newApprovalFixture(t *testing.T) *approvalFixture {
	t.Helper()
	pool := testdb.Postgres(t)
	ctx := context.Background()

	org := uuid.NewString()
	_, err := pool.Exec(ctx,
		`INSERT INTO organizations (id, name, slug) VALUES ($1, $2, $3)`,
		org, "approvals-int-"+org[:8], "approvals-int-"+org[:8])
	require.NoError(t, err, "seed the fixture org")
	f := &approvalFixture{pool: pool, org: org}
	t.Cleanup(func() {
		cleanup, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		_, _ = pool.Exec(cleanup, `DELETE FROM approval_operations WHERE org_id = $1::uuid`, org)
		_, _ = pool.Exec(cleanup, `DELETE FROM organizations WHERE id = $1::uuid`, org)
	})
	return f
}

