// intAcceptance1_WorkingFlow: request (zero TTL → SPI default 15 min) →
// decision by a different human → approved once; a duplicate decision
// resolves once without flipping anything.
func TestIntApprovals_Acceptance1_WorkingFlow(t *testing.T) {
	f := newApprovalFixture(t)
	ctx := context.Background()
	s := NewStore(f.pool)

	op := f.opFor("op-"+uuid.NewString(), "user-1", agentloop.SubjectHuman)
	req := f.reqFor(string(op.ID), "user-1", agentloop.SubjectHuman, "digest-A")

	rec, err := s.Request(ctx, op, req)
	require.NoError(t, err)
	require.NotEmpty(t, rec.ApprovalID, "the durable ApprovalID is generated by the store")
	require.Equal(t, agentloop.ApprovalPending, rec.State)
	require.Equal(t, agentloop.DefaultApprovalTTL, rec.Request.TTL,
		"zero TTL resolves to the SPI default (15 min)")
	require.WithinDuration(t, time.Now().UTC().Add(agentloop.DefaultApprovalTTL), rec.ExpiresAt, 30*time.Second,
		"the absolute deadline is persisted with the request")

	afterGet, err := s.Get(ctx, rec.ApprovalID)
	require.NoError(t, err, "the stored operation is observable by ID independent of any connection")
	require.Equal(t, agentloop.ApprovalPending, afterGet.State)
	require.Equal(t, req.ArgsDigest, afterGet.Request.ArgsDigest)
	require.Equal(t, req.PolicyRef, afterGet.Request.PolicyRef)
	require.Equal(t, req.Initiator, afterGet.Request.Initiator)

	// The decision by a different human resolves the request.
	decided, err := s.Decision(ctx, agentloop.ApprovalDecision{
		ApprovalID: rec.ApprovalID,
		Outcome:    agentloop.DecisionApproved,
		Approver:   "human-2",
	})
	require.NoError(t, err)
	require.Equal(t, agentloop.ApprovalApproved, decided.State)
	require.NotNil(t, decided.Decision)
	require.Equal(t, "human-2", decided.Decision.Approver)
	require.False(t, decided.Decision.DecidedAt.IsZero())

	// Duplicate submission of the same decision resolves ONCE.
	dup, err := s.Decision(ctx, agentloop.ApprovalDecision{
		ApprovalID: rec.ApprovalID,
		Outcome:    agentloop.DecisionApproved,
		Approver:   "human-2",
	})
	require.ErrorIs(t, err, ErrNotPending)
	require.Equal(t, agentloop.ApprovalApproved, dup.State)
	require.Equal(t, decided.Decision.DecidedAt, dup.Decision.DecidedAt,
		"the duplicate must not overwrite the recorded decision")

	// The sweep never touches decided rows: approved is a decision record,
	// not an active window.
	flipped, err := s.ExpirePast(ctx)
	require.NoError(t, err)
	final, err := s.Get(ctx, rec.ApprovalID)
	require.NoError(t, err)
	require.Equal(t, agentloop.ApprovalApproved, final.State,
		"an approved decision record must survive sweeps")
	require.GreaterOrEqual(t, flipped, int64(0))
}

// intAcceptance2_BindingIsExact: the consent is bound to
// subject/server/tool/args-digest/policy-ref — a different args digest is a
// different operation and inherits nothing.
func TestIntApprovals_BindingIsExact(t *testing.T) {
	f := newApprovalFixture(t)
	ctx := context.Background()
	s := NewStore(f.pool)

	op := f.opFor("op-"+uuid.NewString(), "user-1", agentloop.SubjectHuman)
	first, err := s.Request(ctx, op, f.reqFor(string(op.ID), "user-1", agentloop.SubjectHuman, "digest-original"))
	require.NoError(t, err)
	// Same invocation shape, CHANGED args: a new, independent binding.
	second, err := s.Request(ctx, op, f.reqFor(string(op.ID), "user-1", agentloop.SubjectHuman, "digest-changed"))
	require.NoError(t, err)
	require.NotEqual(t, first.ApprovalID, second.ApprovalID)

	_, err = s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: first.ApprovalID, Outcome: agentloop.DecisionApproved, Approver: "human-2"})
	require.NoError(t, err)

	stillPending, err := s.Get(ctx, second.ApprovalID)
	require.NoError(t, err)
	require.Equal(t, agentloop.ApprovalPending, stillPending.State,
		"changed args never inherit the old approval (the old consent is bound to digest-original)")

	pendingList, err := s.PendingByOperation(ctx, op.ID)
	require.NoError(t, err)
	require.Len(t, pendingList, 1)
	require.Equal(t, second.ApprovalID, pendingList[0].ApprovalID)
	require.Equal(t, "digest-changed", pendingList[0].Request.ArgsDigest)
}

// intAcceptance3_ExpirySweepAndLateDecision: the persisted deadline is
// enforced across the sweep, and the late decision answers
// ErrApprovalExpired without reviving anything.
func TestIntApprovals_ExpirySweepAndLateDecision(t *testing.T) {
	f := newApprovalFixture(t)
	ctx := context.Background()
	s := NewStore(f.pool)

	op := f.opFor("op-"+uuid.NewString(), "user-1", agentloop.SubjectHuman)
	req := f.reqFor(string(op.ID), "user-1", agentloop.SubjectHuman, "digest-exp")
	req.TTL = time.Second // policy-configured short window
	rec, err := s.Request(ctx, op, req)
	require.NoError(t, err)
	require.WithinDuration(t, time.Now().UTC().Add(time.Second), rec.ExpiresAt, 2*time.Second)

	// Wait past the deadline WITHOUT the sweep, then decide: the row is
	// still pending (sweeps are periodic), the decision races a
	// past-deadline row — one guarded statement resolves it to expired.
	time.Sleep(1200 * time.Millisecond)
	late, err := s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: rec.ApprovalID, Outcome: agentloop.DecisionApproved, Approver: "human-2"})
	require.ErrorIs(t, err, agentloop.ErrApprovalExpired,
		"a late decision is rejected with the SPI sentinel (I59)")
	require.Equal(t, agentloop.ApprovalExpired, late.State,
		"the expiry materializes at decision time, honestly and durably")

	// A second late decision cannot revive; the answer is the same
	// classification with the terminal record.
	again, err := s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: rec.ApprovalID, Outcome: agentloop.DecisionRejected, Approver: "human-3"})
	require.ErrorIs(t, err, agentloop.ErrApprovalExpired)
	require.Equal(t, agentloop.ApprovalExpired, again.State)

	// A late Cancel on the expired row is also refused: expired is terminal.
	_, err = s.Cancel(ctx, rec.ApprovalID)
	require.ErrorIs(t, err, agentloop.ErrApprovalExpired)

	// The sweep moves pending rows past their deadline (fresh one) to
	// expired; the already-expired row is not double-counted.
	other := f.reqFor(string(op.ID), "user-1", agentloop.SubjectHuman, "digest-sweep")
	other.TTL = time.Second
	p2, err := s.Request(ctx, op, other)
	require.NoError(t, err)
	f.agePastDeadline(t, p2.ApprovalID)
	flipped, err := s.ExpirePast(ctx)
	require.NoError(t, err)
	require.GreaterOrEqual(t, flipped, int64(1))
	swept, err := s.Get(ctx, p2.ApprovalID)
	require.NoError(t, err)
	require.Equal(t, agentloop.ApprovalExpired, swept.State)
}

