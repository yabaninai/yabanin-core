// intAcceptance7_SelfApprovalRules: the seam's I57 invariants hold on live
// rows; the human/service-without-mandate boundary stays with T03.
func TestIntApprovals_SelfApprovalRules(t *testing.T) {
	f := newApprovalFixture(t)
	ctx := context.Background()
	s := NewStore(f.pool)

	// Agent initiator, self-approving "human-2" is forbidden outright.
	op := f.opFor("op-"+uuid.NewString(), "agent-1", agentloop.SubjectAgent)
	agentReq := f.reqFor(string(op.ID), "agent-1", agentloop.SubjectAgent, "digest-selfagent")
	agentReq.RequiresDifferentHuman = false
	agentRec, err := s.Request(ctx, op, agentReq)
	require.NoError(t, err)
	_, err = s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: agentRec.ApprovalID, Outcome: agentloop.DecisionApproved, Approver: "agent-1"})
	require.ErrorIs(t, err, ErrSelfApproval)
	stillPending, err := s.Get(ctx, agentRec.ApprovalID)
	require.NoError(t, err)
	require.Equal(t, agentloop.ApprovalPending, stillPending.State,
		"a refused self-approval leaves the operation pending")

	// RequiresDifferentHuman forbids the initiator even for a human
	// initiator with an (otherwise permitted) self-approval policy.
	op2 := f.opFor("op-"+uuid.NewString(), "user-1", agentloop.SubjectHuman)
	diffReq := f.reqFor(string(op.ID), "user-1", agentloop.SubjectHuman, "digest-diffhuman")
	diffReq.RequiresDifferentHuman = true
	diffRec, err := s.Request(ctx, op2, diffReq)
	require.NoError(t, err)
	_, err = s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: diffRec.ApprovalID, Outcome: agentloop.DecisionApproved, Approver: "user-1"})
	require.ErrorIs(t, err, ErrSelfApproval)

	// Different human satisfies the mandate.
	_, err = s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: diffRec.ApprovalID, Outcome: agentloop.DecisionApproved, Approver: "human-2"})
	require.NoError(t, err)

	// Documented T03 boundary: human initiator without the mandate is not
	// yet policed at store level (approver permissions arrive with T03).
	op3 := f.opFor("op-"+uuid.NewString(), "user-9", agentloop.SubjectHuman)
	selfRec, err := s.Request(ctx, op3, f.reqFor(string(op3.ID), "user-9", agentloop.SubjectHuman, "digest-selfok"))
	require.NoError(t, err)
	_, err = s.Decision(ctx, agentloop.ApprovalDecision{ApprovalID: selfRec.ApprovalID, Outcome: agentloop.DecisionApproved, Approver: "user-9"})
	require.NoError(t, err)
}

